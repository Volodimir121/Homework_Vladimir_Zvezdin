#ifndef LIST_H
#define LIST_H

#include <stddef.h>

/**
 * Коды ошибок для операций над односвязным списком.
 */
typedef enum ListErrorCode {
    LIST_SUCCESS = 0,             /* Операция выполнена успешно */
    LIST_ERR_INVALID_ARGUMENT,    /* Передан некорректный указатель (NULL) */
    LIST_ERR_NO_MEMORY,           /* Ошибка выделения динамической памяти */
    LIST_ERR_NOT_FOUND            /* Элемент не найден в списке */
} ListErrorCode;

/**
 * Непрозрачный тип узла.
 * Определение структуры находится исключительно в файле реализации list.c.
 * Это гарантирует сокрытие деталей реализации и предотвращает утечку указателей на узлы наружу.
 */
typedef struct Node Node;

/**
 * Структура односвязного списка.
 * Хранит указатель на первый узел цепочки и текущее количество элементов.
 */
typedef struct List {
    Node *head;     /* Указатель на головной узел */
    size_t size;    /* Текущее число элементов в списке */
} List;

/**
 * Тип функции обратного вызова для операции обхода (list_traverse).
 * Вызывается для каждого элемента списка по порядку.
 */
typedef void (*ListCallback)(int value);

/* ========================================================================= */
/*                              Операции по ТЗ                              */
/* ========================================================================= */

/**
 * Инициализирует пустой список.
 * @param list Адрес структуры списка.
 * @return LIST_SUCCESS или код ошибки.
 */
ListErrorCode list_init(List *list);

/**
 * Уничтожает список и итеративно освобождает всю память, выделенную под узлы.
 * Безопасен при повторном вызове (идемпотентность).
 * @param list Адрес структуры списка.
 */
void list_destroy(List *list);

/**
 * Вставляет элемент в начало списка (O(1)).
 * @param list Адрес структуры списка.
 * @param value Значение для вставки.
 * @return LIST_SUCCESS или код ошибки.
 */
ListErrorCode list_push_front(List *list, int value);

/**
 * Вставляет элемент в конец списка (O(N), так как нет указателя на хвост).
 * @param list Адрес структуры списка.
 * @param value Значение для вставки.
 * @return LIST_SUCCESS или код ошибки.
 */
ListErrorCode list_push_back(List *list, int value);

/**
 * Удаляет первое вхождение элемента с указанным значением.
 * Корректно обрабатывает удаление первого, срединного и последнего узлов.
 * @param list Адрес структуры списка.
 * @param value Значение удаляемого элемента.
 * @return LIST_SUCCESS, если элемент найден и удален, иначе код ошибки.
 */
ListErrorCode list_remove_first(List *list, int value);

/**
 * Выполняет линейный поиск значения в списке и возвращает его 0-индексированную позицию.
 * @param list Адрес структуры списка.
 * @param value Искомое значение.
 * @param out_position Указатель для записи найденной позиции.
 * @return LIST_SUCCESS, если элемент найден, LIST_ERR_NOT_FOUND если отсутствует,
 *         или код ошибки аргументов.
 */
ListErrorCode list_find(const List *list, int value, size_t *out_position);

/**
 * Выполняет последовательный обход элементов списка от головы к хвосту,
 * вызывая переданную функцию callback для каждого элемента.
 * @param list Адрес структуры списка.
 * @param callback Функция обратного вызова.
 */
void list_traverse(const List *list, ListCallback callback);

/**
 * Возвращает текущее количество элементов в списке (O(1)).
 * @param list Адрес структуры списка.
 * @return Количество элементов в списке (0, если список пуст или передан NULL).
 */
size_t list_size(const List *list);

/**
 * Преобразует код ошибки в читаемое строковое описание на английском (для вывода в консоль).
 * @param error Код ошибки.
 * @return Строка с описанием ошибки.
 */
const char *list_error_to_string(ListErrorCode error);

#endif /* LIST_H */
